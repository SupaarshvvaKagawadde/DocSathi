import type { Profile, Predicate, RulePack, DocumentRecord, EvidenceAnchor } from '../shared/model';
import { emptyProfile } from '../shared/model';
import { profileAnswers } from '../shared/profile';
import { validatePackSources, packScopeHash } from './pack-validation';
import { evidenceHash } from './review-integrity';
import type { PackDossier } from './review-workbook';
import type { BenchmarkManifest } from './benchmark-runner';

function fieldsOf(predicate: Predicate): (keyof Profile)[] {
  if (predicate.op === 'always') return [];
  if (predicate.op === 'not') return fieldsOf(predicate.arg);
  if (predicate.op === 'and' || predicate.op === 'or')
    return [...new Set(predicate.args.flatMap(fieldsOf))];
  if (predicate.op === 'eq' || predicate.op === 'in') return [predicate.field];
  throw Error('Unsupported predicate in the source pack.');
}
export function requirementProfiles(predicate: Predicate): Profile[] {
  let profiles: Profile[] = [{ ...emptyProfile }];
  for (const field of fieldsOf(predicate)) {
    profiles = profiles.flatMap((p) =>
      profileAnswers[field].map((value) => ({ ...p, [field]: value })),
    );
    if (profiles.length > 500)
      throw Error(
        'Predicate profile combinations exceed the review envelope. Split the requirement.',
      );
  }
  return profiles;
}

/** Derive input coverage only. No expected outcomes are generated by this tool. */
export function officialBenchmark(dossier: PackDossier): BenchmarkManifest {
  const checked = validatePackSources(dossier.pack, dossier.snapshots);
  if (checked.scopeHash !== dossier.scopeHash) throw Error('The source dossier hash is stale.');
  const pack = dossier.pack;
  const cases: BenchmarkManifest['cases'] = [];
  for (const requirement of pack.requirements) {
    const oneRule: RulePack = {
      id: pack.id,
      version: pack.version,
      title: pack.title,
      cycle: pack.cycle,
      stage: pack.stage,
      sourceUrl: pack.sourceUrl,
      checkedAt: pack.checkedAt,
      assurance: pack.assurance,
      lifecycle: 'draft',
      requirements: [structuredClone(requirement)],
      sources: pack.sources,
      limitations: pack.limitations,
    };
    const mime = requirement.mime === 'image/jpeg' ? 'image/jpeg' : 'application/pdf';
    const slots = requirement.evidenceSlots?.length ? requirement.evidenceSlots : [''];
    const components = requirement.evidenceMode === 'any' ? [slots[0]] : slots;
    for (const profile of requirementProfiles(requirement.condition)) {
      const packet = {
        id: 'synthetic-packet',
        title: 'Synthetic official-rule case',
        packId: pack.id,
        mode: 'instructions' as const,
        revision: 1,
        profile,
        links: {},
        createdAt: '2026-10-10',
        updatedAt: '2026-10-10',
      };
      const documents: DocumentRecord[] = components.map((_slot, i) => ({
        id: 'd-' + i,
        packetId: packet.id,
        name: 'synthetic-' + i + (mime === 'image/jpeg' ? '.jpg' : '.pdf'),
        mime,
        status: 'ready',
        size: requirement.minBytes ?? Math.min(requirement.maxBytes ?? 1000, 1000),
        pageCount: requirement.minPages ?? 1,
        width: requirement.minWidth ?? Math.min(requirement.maxWidth ?? 600, 600),
        height: requirement.minHeight ?? Math.min(requirement.maxHeight ?? 800, 800),
        hash: 'synthetic-original-' + i,
        createdAt: '2026-10-10',
        pages: [
          {
            number: 1,
            text:
              requirement.expectedText ||
              'Synthetic document; content review explicitly confirmed.',
            method: 'native',
          },
        ],
        ...(requirement.dateCheck
          ? {
              facts: [
                {
                  id: 'date',
                  kind: requirement.dateCheck.field,
                  page: 1,
                  originalText: requirement.dateCheck.reference,
                  value: requirement.dateCheck.reference,
                  confidence: 100,
                  history: [
                    {
                      revision: 1,
                      value: requirement.dateCheck.reference,
                      confirmed: true,
                      reason: 'Inspected the synthetic original date.',
                      actor: 'synthetic-applicant',
                      createdAt: '2026-10-10',
                    },
                  ],
                },
              ],
            }
          : {}),
      }));
      const anchors: EvidenceAnchor[] = components.map((slot, i) => ({
        documentId: 'd-' + i,
        pageFrom: 1,
        pageTo: 1,
        slot,
        review: 'confirmed',
        note: 'Compared this synthetic original with the source-defined content.',
      }));
      const linked = {
        ...packet,
        links: { [requirement.id]: { ...anchors[0], additional: anchors.slice(1) } },
      };
      cases.push({ id: '', scenario: { packet: linked, documents, pack: oneRule } });
      cases.push({ id: '', scenario: { packet, documents: [], pack: oneRule } });
      if (components.length > 1)
        cases.push({
          id: '',
          scenario: {
            packet: {
              ...linked,
              links: { [requirement.id]: { ...anchors[0], additional: anchors.slice(1, -1) } },
            },
            documents,
            pack: oneRule,
          },
        });
    }
  }
  if (cases.length > 2000)
    throw Error('The official benchmark exceeds 2,000 cases. Split the supported scope.');
  cases.sort((a, b) => evidenceHash(a.scenario).localeCompare(evidenceHash(b.scenario)));
  return {
    version: '3',
    author: pack.authoredBy || 'Unrecorded author',
    purpose:
      'Synthetic one-requirement projections of the exact official source pack, covering every declared profile combination with linked and absent originals. No author expected answers are supplied; parser and authenticity review remain separate.',
    sourceScope: { packId: pack.id, version: pack.version, scopeHash: checked.scopeHash },
    cases: cases.map((c, i) => ({ ...c, id: 'case-' + String(i + 1).padStart(4, '0') })),
  };
}

export function verifyOfficialBenchmarkCoverage(pack: RulePack, manifest: BenchmarkManifest) {
  if (
    manifest.sourceScope?.scopeHash !== packScopeHash(pack) ||
    manifest.sourceScope.packId !== pack.id ||
    manifest.sourceScope.version !== pack.version
  )
    throw Error('Official benchmark scope must match the exact reviewed source pack.');
  if (
    manifest.cases.some(
      ({ scenario }) =>
        scenario.pack.id !== pack.id ||
        scenario.pack.version !== pack.version ||
        scenario.pack.cycle !== pack.cycle ||
        scenario.pack.stage !== pack.stage ||
        scenario.pack.requirements.length !== 1 ||
        !pack.requirements.some((r) => r.id === scenario.pack.requirements[0].id),
    )
  )
    throw Error(
      'Every official benchmark scenario must project the declared pack, cycle and stage.',
    );
  for (const requirement of pack.requirements) {
    const cases = manifest.cases.filter(
      (c) => c.scenario.pack.requirements[0]?.id === requirement.id,
    );
    if (
      !cases.length ||
      cases.some((c) => evidenceHash(c.scenario.pack.requirements[0]) !== evidenceHash(requirement))
    )
      throw Error(
        'Every official requirement must have its exact executable rule in the benchmark.',
      );
    for (const profile of requirementProfiles(requirement.condition)) {
      const matching = cases.filter(
        (c) => evidenceHash(c.scenario.packet.profile) === evidenceHash(profile),
      );
      if (
        !matching.some(
          (c) => !!c.scenario.packet.links[requirement.id] && c.scenario.documents.length,
        ) ||
        !matching.some(
          (c) => !c.scenario.packet.links[requirement.id] && !c.scenario.documents.length,
        )
      )
        throw Error(
          'Every source-defined profile combination needs both linked and missing-evidence coverage.',
        );
    }
  }
  return {
    requirements: pack.requirements.length,
    cases: manifest.cases.length,
    scopeHash: manifest.sourceScope.scopeHash,
  };
}
